package io.waves.data

import app.cash.sqldelight.db.QueryResult
import app.cash.sqldelight.db.SqlDriver
import app.cash.sqldelight.driver.jdbc.sqlite.JdbcSqliteDriver
import io.waves.data.db.WavesDatabase
import io.waves.model.EpisodeId
import io.waves.model.PlaybackProgress
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import java.io.File
import java.nio.file.Files
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Upgrade safety of the on-disk database: version snapshots live in src/commonMain/sqldelight/databases
 * (`<n>.db`, generated by `generateCommonMainWavesDatabaseSchema`), migrations in `migrations/<n>.sqm`.
 */
class SchemaMigrationTest {
    private val dir: File = Files.createTempDirectory("waves-migration").toFile()
    private val snapshots = File("src/commonMain/sqldelight/databases")

    @AfterTest fun cleanup() { dir.deleteRecursively() }

    /** A database as written by a version-1 build: the v1 schema snapshot with user_version = 1. */
    private fun v1Database(): File {
        val file = File(dir, "waves.db")
        File(snapshots, "1.db").copyTo(file)
        raw(file) { it.execute(null, "PRAGMA user_version = 1", 0) }
        return file
    }

    private fun <T> raw(file: File, block: (SqlDriver) -> T): T {
        val driver = JdbcSqliteDriver("jdbc:sqlite:${file.absolutePath}")
        return try { block(driver) } finally { driver.close() }
    }

    private fun SqlDriver.strings(sql: String): List<String> = executeQuery(null, sql, { c ->
        val out = mutableListOf<String>()
        while (c.next().value) out += c.getString(0) ?: ""
        QueryResult.Value(out)
    }, 0).value

    private fun SqlDriver.long(sql: String): Long = strings(sql).single().toLong()

    private fun SqlDriver.tables() = strings("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name").toSet()

    /** Normalized CREATE statements, to compare schemas independent of how they were reached. */
    private fun SqlDriver.schemaSql() =
        strings("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name")
            .map { it.replace(Regex("\\s+"), " ").replace("IF NOT EXISTS ", "").trim() }

    @Test fun schemaVersionMatchesSnapshots() {
        assertEquals(6L, WavesDatabase.Schema.version)
        // Every released version needs a snapshot so verifySqlDelightMigration can check its upgrade path.
        for (v in 1..WavesDatabase.Schema.version) assertTrue(File(snapshots, "$v.db").isFile, "missing $v.db")
    }

    @Test fun liveArchivesSavedUnderAnOldSuffixTakeTodays() {
        val file = File(dir, "waves.db")
        File(snapshots, "5.db").copyTo(file)
        val archive = "https://www.youtube.com/feeds/videos.xml?playlist_id=UULVexampleChannel00000000"
        val other = "https://www.youtube.com/feeds/videos.xml?playlist_id=UULVanotherChannel00000000"
        raw(file) { d ->
            d.execute(null, "PRAGMA user_version = 5", 0)
            d.execute(null, "INSERT INTO podcast VALUES ('$archive', '三個水槍手 · Live', NULL, NULL, NULL, NULL, 1, 1000)", 0)
            d.execute(null, "INSERT INTO podcast VALUES ('$other', 'NBC News · Live Archive', NULL, NULL, NULL, NULL, 0, NULL)", 0)
            d.execute(null, "INSERT INTO podcast VALUES ('https://p/feed', 'Live', NULL, NULL, NULL, NULL, 1, 1000)", 0)
        }
        val driver = createDesktopDriver(file)
        try {
            assertEquals(
                listOf("Live", "NBC News · Lived", "三個水槍手 · Lived"),
                driver.strings("SELECT title FROM podcast ORDER BY feedUrl"),
            )
        } finally {
            driver.close()
        }
    }

    @Test fun v1DatabaseIsMigratedAndKeepsItsData() = runBlocking<Unit> {
        val file = v1Database()
        raw(file) { d ->
            assertTrue("download" !in d.tables())
            d.execute(null, "INSERT INTO podcast VALUES ('https://p/feed', 'Pod', 'Ann', NULL, NULL, 42, 1, 1000)", 0)
            d.execute(null, "INSERT INTO podcast VALUES ('https://gone/feed', 'Gone', NULL, NULL, NULL, NULL, 0, 2000)", 0)
            d.execute(null, "INSERT INTO episode VALUES ('https://p/feed', 'g1', 'Ep 1', 'https://p/1.mp3', 5, 60, NULL, NULL)", 0)
            d.execute(null, "INSERT INTO progress VALUES ('https://p/feed', 'g1', 600000, 3600000, 0, 3000)", 0)
            d.execute(null, "INSERT INTO history(feedUrl, guid, episodeTitle, podcastTitle, playedAt, deviceId) VALUES ('https://p/feed', 'g1', 'Ep 1', 'Pod', 4000, 'dev-a')", 0)
            d.execute(null, "INSERT INTO setting VALUES ('deviceId', 'dev-a')", 0)
        }

        val driver = createDesktopDriver(file)
        try {
            assertEquals(WavesDatabase.Schema.version, userVersion(driver))
            assertTrue("download" in driver.tables())
            val repo = SqlLibraryRepository(driver)
            assertEquals(listOf("Pod"), repo.subscriptions.first().map { it.title })
            assertEquals(42L, repo.subscriptions.first().single().appleId)
            assertEquals("dev-a", repo.deviceId())
            assertEquals(
                PlaybackProgress(EpisodeId("https://p/feed", "g1"), 600_000, 3_600_000, false, 3000),
                repo.progress(EpisodeId("https://p/feed", "g1")).first(),
            )
            assertEquals(listOf("dev-a"), repo.history.first().map { it.deviceId })
            assertEquals("Ep 1", repo.episode(EpisodeId("https://p/feed", "g1"))?.title)
            // The unsubscribe tombstone survives too, so it keeps propagating through sync.
            val export = repo.exportSyncState()
            assertEquals(mapOf("https://gone/feed" to false, "https://p/feed" to true),
                export.subscriptions.associate { it.podcast.feedUrl to it.subscribed })
            // The new table is usable.
            WavesDatabase(driver).downloadQueries.insert(
                "https://p/feed", "g1", "Ep 1", "https://p/1.mp3", "Done", 10, 10, "/tmp/x.mp3", null, 1, 2, 3,
            )
            assertEquals(1, WavesDatabase(driver).downloadQueries.all().executeAsList().size)
        } finally {
            driver.close()
        }
    }

    @Test fun migratedSchemaEqualsFreshSchema() {
        val migrated = createDesktopDriver(v1Database()).let { d -> d.schemaSql().also { d.close() } }
        val fresh = createDesktopDriver(File(dir, "fresh.db")).let { d -> d.schemaSql().also { d.close() } }
        assertEquals(fresh, migrated)
    }

    @Test fun v1DatabaseWithRuntimeCreatedDownloadTableMigrates() {
        // Version-1 builds with offline downloads created the table lazily (CREATE_DOWNLOAD_TABLE).
        val file = v1Database()
        raw(file) { d ->
            d.execute(null, io.waves.download.CREATE_DOWNLOAD_TABLE, 0)
            d.execute(null, "INSERT INTO download VALUES ('f', 'g', 't', 'u', 'Done', 1, 1, '/x', NULL, 1, 2, 3)", 0)
        }
        val driver = createDesktopDriver(file)
        try {
            assertEquals(WavesDatabase.Schema.version, userVersion(driver))
            assertEquals(listOf("Done"), driver.strings("SELECT status FROM download"))
        } finally {
            driver.close()
        }
    }

    @Test fun freshDatabaseIsCreatedAtCurrentVersionAndReopenIsNoOp() {
        val file = File(dir, "new/waves.db")
        createDesktopDriver(file).close()
        raw(file) { assertEquals(WavesDatabase.Schema.version, it.long("PRAGMA user_version")) }
        val again = createDesktopDriver(file)
        try {
            assertEquals(WavesDatabase.Schema.version, userVersion(again))
        } finally {
            again.close()
        }
    }

    @Test fun databaseFromNewerAppIsLeftAlone() {
        val file = File(dir, "waves.db")
        createDesktopDriver(file).close()
        raw(file) { d ->
            d.execute(null, "PRAGMA user_version = 99", 0)
            d.execute(null, "CREATE TABLE future (x TEXT)", 0)
        }
        val driver = createDesktopDriver(file)
        try {
            assertEquals(99L, userVersion(driver))
            assertTrue("future" in driver.tables())
        } finally {
            driver.close()
        }
    }

    @Test fun desktopConnectionsUseWalAndBusyTimeout() {
        val driver = createDesktopDriver(File(dir, "waves.db"))
        try {
            assertEquals("wal", driver.strings("PRAGMA journal_mode").single().lowercase())
            assertEquals(5000L, driver.long("PRAGMA busy_timeout"))
            assertEquals(1L, driver.long("PRAGMA foreign_keys"))
            assertEquals(1L, driver.long("PRAGMA synchronous")) // NORMAL
        } finally {
            driver.close()
        }
    }
}
