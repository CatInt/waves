// macOS app: `./gradlew :composeApp:run`, or `:composeApp:packageDmg` for a .dmg
// (`packageReleaseDmg` for the ProGuard-shrunk variant).
compose.desktop {
    application {
        mainClass = "io.waves.MainKt"

        buildTypes.release.proguard {
            configurationFiles.from(project.file("proguard-desktop.pro"))
        }

        nativeDistributions {
            // jpackage is required, and Android Studio's JBR doesn't ship it: point `packaging.javaHome`
            // (local.properties / -P) or WAVES_PACKAGING_JAVA_HOME at a full JDK 17+, e.g. Homebrew openjdk@21.
            // That JDK is also the runtime jlink'd into the app.
            (releaseSigningValue("packaging.javaHome", "WAVES_PACKAGING_JAVA_HOME"))?.let { javaHome = it }
            targetFormats(TargetFormat.Dmg)
            // jlink only bundles the JDK modules listed here: the `suggestRuntimeModules` output (java.sql for the
            // SQLite JDBC driver, jdk.unsupported for sun.misc.Unsafe used by JavaFX/Compose, ...) plus modules
            // reached reflectively or via ServiceLoader that jdeps can't see: java.net.http for Ktor's Java
            // engine and jdk.crypto.ec for TLS handshakes with EC certificates (most podcast CDNs). jdk.httpserver
            // runs the player's loopback StreamRelay.
            modules(
                "java.instrument", "java.management", "java.net.http", "java.sql",
                "jdk.crypto.ec", "jdk.httpserver", "jdk.jfr", "jdk.unsupported",
            )
            packageName = "Waves"
            packageVersion = appVersion
            description = "Podcast player"
            vendor = "Waves"
            copyright = "© 2026 Waves contributors. GNU GPL v3."
            macOS {
                bundleID = "io.waves.desktop"
                appCategory = "public.app-category.music"
                iconFile.set(project.file("icons/waves.icns"))
            }
        }
    }
}

