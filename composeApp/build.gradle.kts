// Google OAuth "Desktop app" client for Drive sync, read from local.properties (never committed) or
// -P / env vars, and compiled into a constant. Empty values build fine; sign-in then reports "not configured".
// See docs/google-drive-setup.md.
val googleOAuthProps = Properties().apply {
    rootProject.file("local.properties").takeIf { it.isFile }?.inputStream()?.use { load(it) }
}
fun googleOAuthValue(key: String, env: String): String =
    (googleOAuthProps.getProperty(key) ?: providers.gradleProperty(key).orNull ?: System.getenv(env)).orEmpty().trim()

val generateGoogleOAuthConfig by tasks.registering {
    val clientId = googleOAuthValue("google.desktop.clientId", "WAVES_GOOGLE_DESKTOP_CLIENT_ID")
    val clientSecret = googleOAuthValue("google.desktop.clientSecret", "WAVES_GOOGLE_DESKTOP_CLIENT_SECRET")
    val outDir = layout.buildDirectory.dir("generated/googleOAuth/desktopMain/kotlin")
    inputs.property("clientId", clientId)
    inputs.property("clientSecret", clientSecret)
    outputs.dir(outDir)
    doLast {
        fun lit(v: String) = "\"" + v.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val file = outDir.get().file("io/waves/sync/GoogleOAuthBuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :composeApp:generateGoogleOAuthConfig from local.properties. Do not edit or commit.
            |package io.waves.sync
            |
            |internal object GoogleOAuthBuildConfig {
            |    const val DESKTOP_CLIENT_ID: String = ${lit(clientId)}
            |    const val DESKTOP_CLIENT_SECRET: String = ${lit(clientSecret)}
            |}
            |""".trimMargin()
        )
    }
}

/** JavaFX native classifier for the build host (desktop apps are packaged per OS/arch anyway). */
val javafxClassifier: String = run {
    val os = System.getProperty("os.name").lowercase()
    val arm = System.getProperty("os.arch").lowercase().let { it == "aarch64" || it == "arm64" }
    when {
        os.contains("mac") -> if (arm) "mac-aarch64" else "mac"
        os.contains("win") -> "win"
        else -> if (arm) "linux-aarch64" else "linux"
    }
}

