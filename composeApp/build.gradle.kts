// Release signing, from local.properties (never committed) or -P / env vars. Without a keystore the release
// build falls back to the debug key so `assembleRelease` always works (fine for testing, not for the Play Store).
fun releaseSigningValue(key: String, env: String): String? =
    (googleOAuthProps.getProperty(key) ?: providers.gradleProperty(key).orNull ?: System.getenv(env))?.trim()?.takeIf { it.isNotEmpty() }

/**
 * Shared app version, MAJOR.MINOR.PATCH (macOS requires MAJOR > 0). Release builds get it from the git tag via
 * `-Pwaves.version=1.2.3` (see .github/workflows/release.yml); local builds without it are development builds.
 */
val releaseVersion: String? = providers.gradleProperty("waves.version").orNull?.trim()?.removePrefix("v")?.takeIf { it.isNotEmpty() }
val appVersion = releaseVersion ?: "1.0.0"
val versionParts = appVersion.split('.').map { it.toInt() }
require(versionParts.size == 3 && versionParts[0] > 0) { "waves.version must be MAJOR.MINOR.PATCH with MAJOR > 0, was $appVersion" }
/** Grows with every release, so Android accepts each new APK as an update. */
val androidVersionCode = versionParts[0] * 1_000_000 + versionParts[1] * 1_000 + versionParts[2]

val generateBuildInfo by tasks.registering {
    val version = appVersion
    val release = releaseVersion != null
    val outDir = layout.buildDirectory.dir("generated/buildInfo/commonMain/kotlin")
    inputs.property("version", version)
    inputs.property("release", release)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("io/waves/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :composeApp:generateBuildInfo. Do not edit or commit.
            |package io.waves
            |
            |object BuildInfo {
            |    const val VERSION: String = "$version"
            |    /** False for local builds (no `-Pwaves.version`), which don't check for updates on their own. */
            |    const val IS_RELEASE: Boolean = $release
            |}
            |""".trimMargin()
        )
    }
}
kotlin.sourceSets.commonMain { kotlin.srcDir(generateBuildInfo) }

